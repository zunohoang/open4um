// Structural and route coverage checks. Does not contact the application.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../..');
const collection=JSON.parse(fs.readFileSync(path.join(here,'ABSlider.postman_collection.json'),'utf8'));
const environment=JSON.parse(fs.readFileSync(path.join(here,'Development.postman_environment.json'),'utf8'));
const inventory=JSON.parse(fs.readFileSync(path.join(here,'coverage.json'),'utf8'));
const names=new Set(); let count=0, scripts=0;
function walk(item) {
  for(const event of item.event||[]) {
    new vm.Script(event.script.exec.join('\n'),{filename:item.name||'collection'}); scripts++;
  }
  if(item.item) return item.item.forEach(walk);
  count++;
  assert(!names.has(item.name),`Duplicate request name ${item.name}`); names.add(item.name);
  assert(item.request.url.startsWith('{{baseUrl}}/'),'Request bypasses development base URL');
  const tests=item.event.find(e=>e.listen==='test').script.exec.join('\n');
  assert(tests.includes('Exact HTTP status') && tests.includes('Success envelope'),`Missing contract assertions: ${item.name}`);
  assert(!tests.includes('console.log'),'Do not log payloads or credentials');
}
walk(collection);
assert.equal(count,inventory.length,'Inventory is out of date');
for(const value of environment.values) {
  if(/password|email|otp|token|mailbox/i.test(value.key)) assert.equal(value.value,'',`Secret/default identity in template ${value.key}`);
}
const normalize=p=>p.split('?')[0].replace(/\{\{[^}]+\}\}/g,':id').replace(/\/$/,'') || '/';
const tested=new Set(inventory.map(r=>r.method+' '+normalize(r.route)));
const prefixes={health:'',auth:'/auth',admin:'/admin',lecture:'/lectures',folder:'/folders'};
const routes=[];
for(const [file,prefix] of Object.entries(prefixes)) {
  const source=fs.readFileSync(path.join(root,'server/src/routes',file+'.routes.ts'),'utf8');
  for(const match of source.matchAll(/\w+Router\.(get|post|patch|delete|put)\(\s*'([^']+)'/g)) {
    const route=match[1].toUpperCase()+' '+normalize(prefix+match[2]);
    assert(tested.has(route),`Uncovered backend route: ${route}`);
    const requests=inventory.filter(r=>r.method+' '+normalize(r.route)===route);
    routes.push({route,requests:requests.map(r=>r.id),statuses:[...new Set(requests.map(r=>r.status))]});
  }
}
const output=['# Backend route coverage','',
  'Generated by `node tests/postman/check.mjs`. This is authored coverage, not a passing execution report.',
  'Successful AI and email flows are separately launched. Dashboard assertions cover contract/date validation, not a full independent statistical audit.',
  '', '| Method and route | Request IDs | Expected statuses |','| --- | --- | --- |',
  ...routes.map(r=>`| \`${r.route}\` | ${r.requests.join(', ')} | ${r.statuses.join(', ')} |`),''];
fs.writeFileSync(path.join(here,'route-coverage.md'),output.join('\n'));
console.log(`OK: ${count} requests, ${scripts} compiled scripts, all ${routes.length} backend routes represented; environment template sanitized.`);
